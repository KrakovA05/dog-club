-- Актуализация текстов, которые живут в БД, а не в коде (08.2026).
--
-- Правки владельца: «собаки до 15 кг» → «собаки мелких пород», «открытый бокс»
-- → «свободное размещение без клеток и вольеров». В репозитории это правится в
-- компонентах, но FAQ и описания тарифов сайт берёт из таблиц — там висели
-- старые формулировки из сидов миграции 001.
--
-- Идемпотентна: replace() не находит подстроку при повторном запуске.
-- Числовой порог 15 кг остаётся в валидации форм и в оферте — меняется только
-- то, что читает клиент.

update public.faq
set answer = replace(answer, 'весом до 15 кг', 'мелких пород')
where answer like '%весом до 15 кг%';

update public.faq
set answer = replace(answer, 'собак и кошек весом до 15 кг', 'собак мелких пород и кошек')
where answer like '%собак и кошек весом до 15 кг%';

update public.prices
set description = replace(description, 'Открытый бокс', 'Свободное размещение без клеток и вольеров')
where description like '%Открытый бокс%';

update public.prices
set description = replace(description, 'Открытые боксы', 'Свободное размещение без клеток и вольеров')
where description like '%Открытые боксы%';
